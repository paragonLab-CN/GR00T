import argparse
from pathlib import Path

import torch


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--packed-file",
        type=str,
        required=True,
        help="Path to step_xxxxxx_packed.pt generated by inspect_candidate_actions.py",
    )
    parser.add_argument(
        "--lewm-action-horizon",
        type=int,
        default=16,
        help="How many action steps LeWM should consume.",
    )
    parser.add_argument(
        "--save-output",
        type=str,
        default="",
        help="Optional path to save LeWM-ready actions.",
    )
    args = parser.parse_args()

    data = torch.load(args.packed_file, map_location="cpu")
    candidate_actions_7d = data["candidate_actions_7d"].float()

    print("candidate_actions_7d:", tuple(candidate_actions_7d.shape))

    B, K, T, D = candidate_actions_7d.shape

    if args.lewm_action_horizon > T:
        raise ValueError(
            f"lewm_action_horizon={args.lewm_action_horizon} is larger than T={T}"
        )

    # 如果 LeWM 只需要前几个 action step，可以在这里截断
    candidate_actions_7d = candidate_actions_7d[:, :, : args.lewm_action_horizon, :]

    B, K, T, D = candidate_actions_7d.shape

    # [B, K, T, D] -> [B*K, T, D]
    lewm_actions = candidate_actions_7d.reshape(B * K, T, D).contiguous()

    print("lewm_actions:", tuple(lewm_actions.shape))

    for i in range(B * K):
        print(f"candidate {i} first action:", lewm_actions[i, 0])

    if args.save_output:
        save_path = Path(args.save_output)
        save_path.parent.mkdir(parents=True, exist_ok=True)

        torch.save(
            {
                "lewm_actions": lewm_actions,
                "B": B,
                "K": K,
                "T": T,
                "D": D,
                "note": "lewm_actions shape is [B*K, T, D]",
            },
            save_path,
        )
        print("Saved LeWM-ready actions to:", save_path)


if __name__ == "__main__":
    main()
